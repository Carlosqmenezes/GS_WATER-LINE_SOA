CREATE TABLE envios (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alerta_id      BIGINT                   NOT NULL,
    inscricao_id   BIGINT,
    destino        VARCHAR(20)              NOT NULL,
    canal          VARCHAR(20),
    status         VARCHAR(20)              NOT NULL,
    registrado_em  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_envios_alerta FOREIGN KEY (alerta_id) REFERENCES alertas (id) ON DELETE CASCADE,
    CONSTRAINT fk_envios_inscricao FOREIGN KEY (inscricao_id) REFERENCES inscricoes (id) ON DELETE SET NULL,
    CONSTRAINT ck_envios_destino CHECK (destino IN ('INSCRITO', 'CENTRAL')),
    CONSTRAINT ck_envios_status CHECK (status IN ('ENVIADO', 'FALHOU')),
    CONSTRAINT ck_envios_canal CHECK (
        (destino = 'CENTRAL' AND canal IS NULL) OR (destino = 'INSCRITO' AND canal IS NOT NULL)
    )
);

CREATE INDEX ix_envios_alerta ON envios (alerta_id);
CREATE INDEX ix_envios_inscricao ON envios (inscricao_id);
