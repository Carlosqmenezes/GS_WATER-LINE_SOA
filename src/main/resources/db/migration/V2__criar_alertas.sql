CREATE TABLE alertas (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alerta_origem_id     INTEGER                  NOT NULL,
    nivel                VARCHAR(20)              NOT NULL,
    mensagem             VARCHAR(500)             NOT NULL,
    boca_de_lobo_id      INTEGER                  NOT NULL,
    codigo_boca_de_lobo  VARCHAR(20)              NOT NULL,
    endereco             VARCHAR(200)             NOT NULL,
    latitude             DOUBLE PRECISION         NOT NULL,
    longitude            DOUBLE PRECISION         NOT NULL,
    criado_em            TIMESTAMP WITH TIME ZONE NOT NULL,
    expira_em            TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_alertas_alerta_origem UNIQUE (alerta_origem_id),
    CONSTRAINT ck_alertas_nivel CHECK (nivel IN ('ALERTA_PRECOCE', 'EMERGENCIA')),
    CONSTRAINT ck_alertas_validade CHECK (expira_em > criado_em)
);

CREATE INDEX ix_alertas_expira_em ON alertas (expira_em);
CREATE INDEX ix_alertas_localizacao ON alertas (latitude, longitude);
