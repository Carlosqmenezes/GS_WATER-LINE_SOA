CREATE TABLE inscricoes (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo         VARCHAR(20)              NOT NULL,
    nome         VARCHAR(100)             NOT NULL,
    contato      VARCHAR(120)             NOT NULL,
    canal        VARCHAR(20)              NOT NULL,
    endereco     VARCHAR(200)             NOT NULL,
    latitude     DOUBLE PRECISION         NOT NULL,
    longitude    DOUBLE PRECISION         NOT NULL,
    raio_metros  INTEGER                  NOT NULL,
    criada_em    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_inscricoes_tipo CHECK (tipo IN ('MORADOR', 'COMERCIANTE')),
    CONSTRAINT ck_inscricoes_canal CHECK (canal IN ('SMS', 'WHATSAPP', 'EMAIL')),
    CONSTRAINT ck_inscricoes_raio CHECK (raio_metros BETWEEN 50 AND 2000),
    CONSTRAINT ck_inscricoes_latitude CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_inscricoes_longitude CHECK (longitude BETWEEN -180 AND 180),
    CONSTRAINT uk_inscricoes_canal_contato UNIQUE (canal, contato)
);

CREATE INDEX ix_inscricoes_localizacao ON inscricoes (latitude, longitude);
